CREATE TABLE IF NOT EXISTS admins (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, last_login DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, slug VARCHAR(140) NOT NULL UNIQUE,
 name_ar VARCHAR(160) NOT NULL, name_fr VARCHAR(160) NOT NULL, name_en VARCHAR(160) NOT NULL,
 image VARCHAR(255) NULL, icon VARCHAR(40) DEFAULT 'grid', sort_order INT DEFAULT 0, active TINYINT(1) DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, category_id BIGINT UNSIGNED NULL,
 slug VARCHAR(180) UNIQUE NOT NULL, sku VARCHAR(90) NULL,
 name_ar VARCHAR(250) NOT NULL, name_fr VARCHAR(250) NOT NULL, name_en VARCHAR(250) NOT NULL,
 description_ar TEXT NULL,description_fr TEXT NULL,description_en TEXT NULL,
 price DECIMAL(12,2) NOT NULL,compare_at_price DECIMAL(12,2) NOT NULL DEFAULT 0,
 stock INT UNSIGNED NOT NULL DEFAULT 0, image VARCHAR(255) NULL,
 featured TINYINT(1) DEFAULT 0, active TINYINT(1) DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_product_cat FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE SET NULL,
 INDEX idx_listing (active,featured,created_at), INDEX idx_cat (category_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS product_variants (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL,
 size VARCHAR(80) NOT NULL DEFAULT '',color VARCHAR(80) NOT NULL DEFAULT '',sku VARCHAR(90) NULL,
 price_adjustment DECIMAL(10,2) NOT NULL DEFAULT 0, stock INT UNSIGNED NOT NULL DEFAULT 0,
 CONSTRAINT fk_variant_prod FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
 INDEX idx_varprod (product_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS product_images (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, image VARCHAR(255) NOT NULL,sort_order INT DEFAULT 0,
 CONSTRAINT fk_gallery_prod FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS coupons (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) NOT NULL UNIQUE,
 discount_type ENUM('percent','fixed') NOT NULL DEFAULT 'percent',amount DECIMAL(10,2) NOT NULL,
 min_subtotal DECIMAL(10,2) DEFAULT 0,max_uses INT DEFAULT 0,used_count INT DEFAULT 0,
 expires_at DATETIME NULL,active TINYINT(1) DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,order_number VARCHAR(32) NOT NULL UNIQUE,
 customer_name VARCHAR(150) NOT NULL,customer_phone VARCHAR(20) NOT NULL,city VARCHAR(120) NOT NULL,
 address VARCHAR(300) NULL,notes TEXT NULL,
 subtotal DECIMAL(12,2) NOT NULL,discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
 shipping_fee DECIMAL(12,2) NOT NULL DEFAULT 0,total DECIMAL(12,2) NOT NULL,
 coupon_code VARCHAR(50) NULL,payment_method VARCHAR(32) NOT NULL DEFAULT 'cod',
 status ENUM('new','confirmed','preparing','shipped','delivered','cancelled') NOT NULL DEFAULT 'new',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_created(created_at), INDEX idx_status(status), INDEX idx_phone(customer_phone)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,order_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NULL,variant_id BIGINT UNSIGNED NULL,sku VARCHAR(90) NULL,
 product_name VARCHAR(250) NOT NULL,variant_label VARCHAR(180) NULL,qty INT UNSIGNED NOT NULL,
 unit_price DECIMAL(12,2) NOT NULL,line_total DECIMAL(12,2) NOT NULL,
 CONSTRAINT fk_items_order FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 CONSTRAINT fk_items_product FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL,
 CONSTRAINT fk_items_variant FOREIGN KEY(variant_id) REFERENCES product_variants(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS settings (name VARCHAR(80) PRIMARY KEY,value TEXT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS visitors (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,fingerprint CHAR(64) UNIQUE NOT NULL,
 first_seen TIMESTAMP DEFAULT CURRENT_TIMESTAMP,last_seen TIMESTAMP DEFAULT CURRENT_TIMESTAMP,views INT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,admin_id BIGINT UNSIGNED NULL,action VARCHAR(80) NOT NULL,detail VARCHAR(400) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,INDEX idx_audit_created(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,ip_hash CHAR(64) NOT NULL,
 attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,INDEX idx_login_attempt(ip_hash,attempted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS order_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,ip_hash CHAR(64) NOT NULL,attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_order_attempts(ip_hash,attempted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
